package arrays;

class Basic {
    public static void main(String[] args) {
        int []  arr = {3,5,8,6,7,2,4,};
        int length = arr.length;
        System.out.println("Length of the array is: " + length);
        System.out.println("First element of the array is: " + arr[0]);
        System.out.println("Last element of the array is: " + arr[length-1]);
    }
}